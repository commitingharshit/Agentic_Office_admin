#!/usr/bin/env node
// Writes database/SCHEMA.md from a migrated database: every table with its purpose, columns, keys, indexes and who may touch it.
//   DATABASE_URL=postgres://ao_owner:…@host/agentic_office node database/tools/schema-doc.ts [--check]
// --check exits 1 when the file on disk differs (CI uses it so the dictionary cannot rot).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'SCHEMA.md');
const c = new pg.Client({ connectionString: process.env.DATABASE_URL });
await c.connect();
const q = async (sql: string) => (await c.query(sql)).rows;
const tables = await q(`SELECT c.relname AS name, obj_description(c.oid) AS purpose, c.relrowsecurity AS rls
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relkind IN ('r','p') AND c.relname <> 'schema_migrations' ORDER BY c.relname`);
const cols = await q(`SELECT table_name, column_name, data_type, udt_name, is_nullable, column_default, ordinal_position FROM information_schema.columns WHERE table_schema = 'public' ORDER BY table_name, ordinal_position`);
const cons = await q(`SELECT conrelid::regclass::text AS t, contype, pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE connamespace = 'public'::regnamespace ORDER BY 1, contype, conname`);
const idx = await q(`SELECT tablename AS t, indexdef FROM pg_indexes WHERE schemaname = 'public' ORDER BY tablename, indexname`);
const grants = await q(`SELECT table_name AS t, grantee, string_agg(privilege_type, ', ' ORDER BY privilege_type) AS p FROM information_schema.role_table_grants WHERE table_schema = 'public' AND grantee LIKE 'ao\\_%' GROUP BY 1, 2 ORDER BY 1, 2`);
await c.end();

const group = (n: string) => n.startsWith('marketplace_') ? 'Marketplace' : /^(plans?|plan_|subscription|credit_|usage_events|coupon|api_keys|entitlements|payment_|invoices)/.test(n) ? 'Billing, plans and credits'
  : /^(campaign|creative|promo_|placements|media_jobs|releases|release_|email_|webhook_events|user_promo)/.test(n) ? 'Growth and email'
  : /^(service_status|status_checks|help_)/.test(n) ? 'Status and help' : /^(auth_|oauth_|device|sign_in|admin_|access_requests)/.test(n) ? 'Identity and administration'
  : /^(feature_flags|announcement|support_)/.test(n) ? 'Operations' : /^(run_steps|verification_results|usage_consent|session|agent_runs|document_revisions|memory_references|sync_cursors|workspaces)/.test(n) ? 'Sync and telemetry' : 'Core';
const by = new Map<string, typeof tables>();
for (const t of tables) { const g = group(t.name); by.set(g, [...(by.get(g) ?? []), t]); }

const L: string[] = ['# Database schema', '', 'Generated by `node database/tools/schema-doc.ts` from the migrated database. Do not edit by hand: change a migration and regenerate.', '',
  `${tables.length} tables. Row-level security is on where marked. Four database roles: \`ao_app\` (the API, as the signed-in person), \`ao_readonly\`, \`ao_admin\` (the admin API) and \`ao_billing\`; \`ao_auth\` serves sign-in.`, ''];
for (const [g, ts] of [...by].sort((a, b) => a[0].localeCompare(b[0]))) {
  L.push(`## ${g}`, '');
  for (const t of ts) {
    L.push(`### ${t.name}${t.rls ? '  (row-level security)' : ''}`, '', t.purpose ?? '_No description._', '', '| Column | Type | Null | Default |', '|---|---|---|---|');
    for (const k of cols.filter((x) => x.table_name === t.name)) L.push(`| ${k.column_name} | ${k.data_type === 'ARRAY' ? k.udt_name.replace(/^_/, '') + '[]' : k.data_type} | ${k.is_nullable === 'YES' ? 'yes' : 'no'} | ${k.column_default ? '`' + String(k.column_default).replace(/\|/g, '\\|').slice(0, 60) + '`' : ''} |`);
    const cs = cons.filter((x) => x.t === t.name);
    if (cs.length) L.push('', '**Constraints**', ...cs.map((x) => `- ${({ p: 'primary key', f: 'foreign key', u: 'unique', c: 'check', x: 'exclude' } as Record<string, string>)[x.contype]}: \`${x.def.replace(/\s+/g, ' ')}\``));
    const ix = idx.filter((x) => x.t === t.name);
    if (ix.length) L.push('', '**Indexes**', ...ix.map((x) => `- \`${x.indexdef.replace(/^CREATE (UNIQUE )?INDEX \w+ ON (public\.)?\w+ /, '$1').replace(/\s+/g, ' ')}\``));
    const gr = grants.filter((x) => x.t === t.name);
    if (gr.length) L.push('', '**Grants**: ' + gr.map((x) => `${x.grantee} (${x.p})`).join('; '));
    L.push('');
  }
}
const text = L.join('\n');
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (cur !== text) { console.error('database/SCHEMA.md is out of date: run node database/tools/schema-doc.ts'); process.exit(1); }
  console.log('SCHEMA.md is current');
} else { writeFileSync(out, text); console.log(`wrote ${out} (${tables.length} tables)`); }
