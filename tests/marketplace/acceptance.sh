#!/usr/bin/env bash
# Marketplace acceptance run (Plan 4 Task 18): local or nightly, NOT hosted-PR CI. It needs a display, the fork build (apps/desktop/out and
# .build/electron), officecli, the Rust kernels and Hermes. It builds nothing: a missing prerequisite makes that row SKIPPED with the reason,
# never PASS. A flow is PASS only if its script exited 0 (every step ran); exit code 2 from a flow means "incomplete" (a skipped step).
#
#   tests/marketplace/acceptance.sh [--out docs/audits/marketplace-acceptance-<date>.md] [--allow-skip <names>] [--ports <cdp>]
#
# Never touches the user's real ~/.hermes, profile or the CDP ports 9351/9338: the flows use throwaway homes and the port passed here
# (default 9363). The result table is written to --out and printed.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$ROOT/docs/audits/marketplace-acceptance-$(date +%Y-%m-%d).md"; ALLOW=""; PORT=9363
while [ $# -gt 0 ]; do case "$1" in --out) OUT="$2"; shift ;; --allow-skip) ALLOW="$2"; shift ;; --ports) PORT="$2"; shift ;; *) echo "unknown argument: $1" >&2; exit 2 ;; esac; shift; done
case "$PORT" in 9351|9338|9361) echo "refusing to use port $PORT: it belongs to the user's window or another session" >&2; exit 2 ;; esac
LOGS="${TMPDIR:-/tmp}/marketplace-acceptance"; mkdir -p "$LOGS"
ROWS=""; FAILS=0; SKIPS=0
row() { ROWS="$ROWS| $1 | $2 | $3 | $4 | $5 |
"; }
run() { # <flow-no> <name> <real-ui> <real-hermes> <cmd...>
	local no="$1" name="$2" ui="$3" hermes="$4"; shift 4
	"$@" >"$LOGS/flow-$no.log" 2>&1; local rc=$?
	case $rc in
		0) row "$no" "$name" "$ui" "$hermes" "PASS" ;;
		2) row "$no" "$name" "$ui" "$hermes" "SKIPPED (incomplete: a step was skipped, see $LOGS/flow-$no.log)"; SKIPS=$((SKIPS + 1)) ;;
		*) row "$no" "$name" "$ui" "$hermes" "FAIL (exit $rc, see $LOGS/flow-$no.log)"; FAILS=$((FAILS + 1)) ;;
	esac
}
skipped() { row "$1" "$2" "$3" "$4" "SKIPPED ($5)"; SKIPS=$((SKIPS + 1)); }

# prerequisites, each named
HAVE_DISPLAY=1; [ "$(uname)" = Darwin ] || [ -n "${DISPLAY:-}" ] || HAVE_DISPLAY=0
HAVE_FORK=0; [ -x "$ROOT/apps/desktop/.build/electron/Agentic Office.app/Contents/MacOS/AgenticOffice" ] && [ -d "$ROOT/apps/desktop/out" ] && HAVE_FORK=1
HAVE_OFFICECLI=0; command -v officecli >/dev/null 2>&1 && HAVE_OFFICECLI=1
HAVE_KERNELS=0; [ -x "$ROOT/kernels/target/release/xlsx-context" ] && HAVE_KERNELS=1

# (a) the gates (never rendered as a flow row; their tally is the first row)
"$ROOT/tests/marketplace/gates.sh" ${ALLOW:+--allow-skip "$ALLOW"} >"$LOGS/gates.log" 2>&1; GRC=$?
tail -1 "$LOGS/gates.log" > "$LOGS/gates.tally"
row "-" "gates (marketplace-gates.sh)" "no" "partly" "$([ $GRC -eq 0 ] && echo PASS || echo "FAIL: $(cat "$LOGS/gates.tally")")"; [ $GRC -eq 0 ] || FAILS=$((FAILS + 1))

# (b) real-window flows: brief flows 1 to 8 (discover, install, use template and skill, unsafe skill and tamper, update with local edits,
#     needs configuration) plus offline, revoke, the signed-in gate and the AX dialog, all in scripts/e2e/plan/marketplace-flow.mjs
if [ $HAVE_DISPLAY = 1 ] && [ $HAVE_FORK = 1 ] && [ $HAVE_OFFICECLI = 1 ]; then
	run "1-8" "marketplace-flow.mjs (window, real Hermes in a throwaway home)" yes yes node "$ROOT/scripts/e2e/plan/marketplace-flow.mjs" --out "$LOGS/flow-out" --port "$PORT" ${ALLOW:+--allow-skip "$ALLOW"}
	run "reg" "ui-flow.mjs (regression)" yes yes node "$ROOT/scripts/e2e/plan/ui-flow.mjs" --out "$LOGS/ui-out" --port "$PORT"
else
	why="needs"; [ $HAVE_DISPLAY = 1 ] || why="$why a display;"; [ $HAVE_FORK = 1 ] || why="$why the fork build (apps/desktop/out and .build/electron);"; [ $HAVE_OFFICECLI = 1 ] || why="$why officecli;"
	skipped "1-8" "marketplace-flow.mjs" yes yes "$why"
	skipped "reg" "ui-flow.mjs (regression)" yes yes "$why"
fi
# (c) the per-type flows (no window; real Hermes, real handlers)
for t in hook memory routine bridge workflow connector configure agent; do
	f="$ROOT/scripts/e2e/plan/marketplace-$t-flow.mjs"; [ -f "$f" ] || continue
	run "type-$t" "marketplace-$t-flow.mjs" no yes node "$f"
done
# (d) a freshly published template and skill through the real verification pipeline
if [ $HAVE_OFFICECLI = 1 ] && [ $HAVE_KERNELS = 1 ]; then run "verify" "verification eval (real officecli and kernels)" no no bash -c "cd '$ROOT/services/api' && npm run eval:verification"
else skipped "verify" "verification eval" no no "needs officecli and the built kernels"; fi
# (e) the structural budgets
run "bench" "marketplace-bench --check" no no node "$ROOT/tests/marketplace/bench/run.mjs" --check --no-server

{
	echo "# Marketplace acceptance run, $(date +%Y-%m-%d)"; echo
	echo "Machine: $(uname -sm); commit $(git -C "$ROOT" rev-parse --short HEAD)$(git -C "$ROOT" diff --quiet || echo ' (dirty tree)'). Generated by tests/marketplace/acceptance.sh."
	echo "A row is PASS only if its command exited 0 with every step run. SKIPPED rows say why; nothing skipped is a pass."; echo
	echo "| # | what | real UI | real Hermes | result |"; echo "|---|---|---|---|---|"; printf '%s' "$ROWS"; echo
	echo "Truth table (computed from the tree):"; echo; echo '```'; node "$ROOT/tests/marketplace/truth-table.mjs"; echo '```'
} > "$OUT"
cat "$OUT"
echo; echo "written to $OUT; $FAILS failed, $SKIPS skipped"
[ $FAILS -eq 0 ]
